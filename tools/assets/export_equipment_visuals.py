"""Export PTClassic equipment resource tables; runtime never reads original_references."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
source = root / 'original_references/PTClassic-master/src'

def clean(path):
    text = path.read_text(encoding='latin1')
    text = re.sub(r'//[^\n]*', '', text)
    return re.sub(r'/\*.*?\*/', '', text, flags=re.S)

items = clean(source / 'sinbaram/sinItem.cpp').split('sITEM sItem[MAX_ITEM] = {', 1)[1].split('};', 1)[0]
rows = re.findall(r'\{([^{}]+)\}', items)
character = clean(source / 'character.cpp')
village_bones = {}
for table, bone in [
    ('dwItemCodeFromVillage', ''),
    ('dwItemCodeFromVillage_Bow', 'Bip in-cro'),
    ('dwItemCodeFromVillage_Cross', 'Bip in-bow'),
]:
    body = re.search(r'\b' + table + r'\[\]\s*=\s*\{([^}]+)\}', character).group(1)
    for family, ordinal in re.findall(r'sin(\w+)\s*\|\s*sin(\d+)', body):
        village_bones[family + ordinal] = bone

entries = []
for index, row in enumerate(rows):
    strings = re.findall(r'"([^"\n]*)"', row)
    if len(strings) >= 4:
        key = strings[1]
        entries.append((key, index, strings[3], 'INVENTORY_POS_LHAND' in row, village_bones.get(key, 'Bip in01')))
armor = clean(source / 'playmodel.h').split('char *szArmorNumFile[MAX_JOBNUM][ARMOR_FILE_MAX] = {', 1)[1].split('};', 1)[0]
armors = [re.findall(r'"([^"\n]+)"', row) for row in re.findall(r'\{([^{}]+)\}', armor)]
assert len(armors) == 8 and all(len(row) == 54 for row in armors)

def remap_armor_prefix(row, body_prefix, costume_prefix):
    result = []
    for path in row:
        stem = Path(path).stem
        suffix = re.search(r'(\d+)$', stem)
        if suffix is None:
            raise ValueError(f'Armor resource has no numeric suffix: {path}')

        prefix = costume_prefix if stem.casefold().startswith('c') else body_prefix
        result.append(prefix + suffix.group(1) + '.inx')
    return result

# PTClassic's creation source adds Assassin as E and Shaman as mE after playmodel.h's original eight
# rows. Their armor/costume resources retain the same ordinal suffix contract as the existing classes.
# Derive both complete 54-entry rows from that contract instead of maintaining a second manual table.
armors.append(remap_armor_prefix(armors[0], 'E', 'Ce'))
armors.append(remap_armor_prefix(armors[4], 'mE', 'Cme'))
assert len(armors) == 10 and all(len(row) == 54 for row in armors)
lines = ['// Generated by tools/assets/export_equipment_visuals.py from PTClassic sinItem.cpp/playmodel.h/character.cpp/HoLogin.cpp.',
         'namespace PristonTale.Gameplay.World.Remote;', '', 'internal static class EquipmentVisualTables', '{',
         '    internal static readonly (string Key, int MotionIndex, string Mesh, bool LeftHand, string VillageBone)[] Items =', '    [']
for key, index, mesh, left_hand, village_bone in entries:
    lines.append(f'        ({json.dumps(key)}, {index}, {json.dumps(mesh)}, {str(left_hand).lower()}, {json.dumps(village_bone)}),')
lines += ['    ];', '', '    internal static readonly string[][] Armors =', '    [']
for row in armors:
    lines += ['        [']
    for i in range(0, len(row), 8):
        lines.append('            ' + ', '.join(json.dumps(Path(p).stem + '.inx') for p in row[i:i+8]) + ',')
    lines += ['        ],']
lines += ['    ];', '}']
(root / 'Client/PristonTale.Gameplay/World/Remote/EquipmentVisualTables.cs').write_text('\n'.join(lines) + '\n')
print(f'Exported {len(entries)} items and {len(armors)} armor tables')

# Equipment legality belongs to the shared authority, independently of presentation paths.
families = {
    'WA1': ('Axe', 'Weapon'), 'WC1': ('Claw', 'Weapon'), 'WH1': ('Hammer', 'Weapon'),
    'WM1': ('Staff', 'Weapon'), 'WP1': ('Pole', 'Weapon'), 'WS1': ('Bow', 'Weapon'),
    'WS2': ('Sword', 'Weapon'), 'WT1': ('ThrowingWeapon', 'Weapon'),
    'DA1': ('Armor', 'Armor'), 'DA2': ('Armor', 'Armor'), 'DS1': ('Shield', 'OffHand'),
}
metadata = {}
for row in rows:
    strings = re.findall(r'"([^"\n]*)"', row)
    if len(strings) < 4:
        continue
    key = strings[1]
    if key[:3].upper() not in families:
        continue
    kind, slot = families[key[:3].upper()]
    metadata.setdefault(key, (kind, slot, 'ITEM_CLASS_WEAPON_TWO' in row))
lines = [
    '// Generated by tools/assets/export_equipment_visuals.py from PTClassic sinItem.cpp.',
    'using PristonTale.Simulation.Characters;', '',
    'namespace PristonTale.Simulation.Items;', '',
    'public static class ItemEquipmentMetadata', '{',
    '    private static readonly Dictionary<string, (ItemKind Kind, EquipmentSlot Slot, bool TwoHanded)> Entries = new(StringComparer.OrdinalIgnoreCase)',
    '    {'
]
for key, (kind, slot, two_handed) in metadata.items():
    lines.append(f'        [{json.dumps(key)}] = (ItemKind.{kind}, EquipmentSlot.{slot}, {str(two_handed).lower()}),')
lines += [
    '    };', '',
    '    public static ItemDefinition Apply(ItemDefinition definition)', '    {',
    '        if (!Entries.TryGetValue(definition.CatalogKey, out var metadata))', '        {',
    '            return definition;', '        }', '',
    '        return definition with { Kind = metadata.Kind, EquipSlot = metadata.Slot, TwoHanded = metadata.TwoHanded };',
    '    }', '}'
]
(root / 'Shared/PristonTale.Simulation/Items/ItemEquipmentMetadata.cs').write_text('\n'.join(lines) + '\n')
print(f'Exported {len(metadata)} weapon/armor/shield equipment contracts')
