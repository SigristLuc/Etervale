"""Prepare the repository UI font at development time; no font conversion runs during gameplay."""

import argparse
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTCollection
from fontTools.varLib.instancer import instantiateVariableFont


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("collection", type=Path)
    parser.add_argument("license", type=Path)
    arguments = parser.parse_args()
    root = Path(__file__).resolve().parents[2]
    destination = root / "assets/Hud/Fonts"
    destination.mkdir(parents=True, exist_ok=True)

    collection = TTCollection(arguments.collection, lazy=True)
    font = next(font for font in collection.fonts if font["name"].getDebugName(1) == "Noto Sans CJK KR")
    ranges = [(32, 126), (160, 591), (880, 1023), (1024, 1279), (8192, 8303), (12593, 12686), (44032, 55203)]
    codepoints = {value for start, end in ranges for value in range(start, end + 1)}
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
    options.name_languages = [0x409]
    options.name_legacy = True
    processor = subset.Subsetter(options=options)
    processor.populate(unicodes=codepoints)
    processor.subset(font)
    # This derivative serves horizontal game UI. Remove vertical variation/origin tables before
    # instancing: fontTools cannot update VORG from VVAR, and those tables are not used by this renderer.
    for table in ["VORG", "VVAR", "vhea", "vmtx"]:
        if table in font:
            del font[table]
    font = instantiateVariableFont(font, {"wght": 400}, inplace=True)
    names = {1: "Priston UI Sans", 2: "Regular", 3: "PristonUISans-Regular-1", 4: "Priston UI Sans Regular", 6: "PristonUISans-Regular", 16: "Priston UI Sans", 17: "Regular"}
    for name_id, value in names.items():
        font["name"].setName(value, name_id, 3, 1, 0x409)

    font.save(destination / "PristonUiSans-Regular.otf")
    shutil.copyfile(arguments.license, destination / "OFL.txt")

    supported = sorted(codepoints.intersection(font.getBestCmap()))
    regions = []
    for value in supported:
        if regions and value == regions[-1][1] + 1:
            regions[-1][1] = value
        else:
            regions.append([value, value])
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tools/ui/build_font.py; baked glyphs avoid runtime font rasterization. -->',
        '<XnaContent xmlns:Graphics="Microsoft.Xna.Framework.Content.Pipeline.Graphics">',
        '  <Asset Type="Graphics:FontDescription">',
        '    <FontName>../../../../assets/Hud/Fonts/PristonUiSans-Regular.otf</FontName>',
        '    <Size>18</Size>',
        '    <Spacing>0</Spacing>',
        '    <UseKerning>true</UseKerning>',
        '    <Style>Regular</Style>',
        '    <DefaultCharacter>?</DefaultCharacter>',
        '    <CharacterRegions>',
    ]
    for start, end in regions:
        lines.extend([
            '      <CharacterRegion>',
            f'        <Start>&#{start};</Start>',
            f'        <End>&#{end};</End>',
            '      </CharacterRegion>',
        ])
    lines.extend(['    </CharacterRegions>', '  </Asset>', '</XnaContent>', ''])
    (root / 'Client/PristonTale/Content/Fonts/UI.spritefont').write_text('\n'.join(lines), encoding='utf-8')


if __name__ == "__main__":
    main()
