    public static int MaximumLevel => Thresholds.Length;

    public static ulong ForLevel(int level)
    {
        if (level < 1 || level > MaximumLevel)
        {
            throw new ArgumentOutOfRangeException(nameof(level));
        }

        return Thresholds[level - 1];
    }

    public static int LevelFor(ulong experience)
    {
        var index = Array.BinarySearch(Thresholds, experience);
        return index >= 0 ? index + 1 : ~index;
    }
